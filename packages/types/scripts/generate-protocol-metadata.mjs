import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = path.resolve(import.meta.dirname, '..')
const outFile = path.join(root, 'src/generated/protocol-schema-metadata.ts')

const singboxSchemaPath = require.resolve('@black-duty/sing-box-schema/schema.json')
const metaPackagePath = require.resolve('meta-json-schema/package.json')
const mihomoSchemaPath = path.join(path.dirname(metaPackagePath), 'schemas/meta-json-schema.json')

const singboxSchema = JSON.parse(fs.readFileSync(singboxSchemaPath, 'utf8'))
const mihomoSchema = JSON.parse(fs.readFileSync(mihomoSchemaPath, 'utf8'))
const singboxPackage = JSON.parse(fs.readFileSync(require.resolve('@black-duty/sing-box-schema/package.json'), 'utf8'))
const mihomoPackage = JSON.parse(fs.readFileSync(metaPackagePath, 'utf8'))

const MANAGED_SINGBOX_TYPES = new Set([
  'anytls',
  'direct',
  'http',
  'hysteria',
  'hysteria2',
  'shadowsocks',
  'shadowsocksr',
  'shadowtls',
  'socks',
  'ssh',
  'trojan',
  'tuic',
  'vless',
  'vmess',
])

const MANAGED_SINGBOX_ENDPOINT_TYPES = new Set(['wireguard'])

const MANAGED_MIHOMO_TYPES = new Set([
  'anytls',
  'direct',
  'http',
  'hysteria',
  'hysteria2',
  'reject',
  'ss',
  'ssr',
  'socks5',
  'ssh',
  'trojan',
  'tuic',
  'vless',
  'vmess',
  'wireguard',
])

function schemaTypeName(schema) {
  const type = schema?.properties?.type
  if (typeof type?.const === 'string') return type.const
  if (Array.isArray(type?.enum) && typeof type.enum[0] === 'string') return type.enum[0]
  return undefined
}

function collectProperties(schema, bucket = new Set()) {
  if (!schema || typeof schema !== 'object') return bucket
  if (schema.properties && typeof schema.properties === 'object') {
    for (const key of Object.keys(schema.properties)) bucket.add(key)
  }
  for (const key of ['allOf', 'anyOf', 'oneOf']) {
    const entries = schema[key]
    if (Array.isArray(entries)) {
      for (const entry of entries) collectProperties(entry, bucket)
    }
  }
  return bucket
}

function extractSingboxOutbounds() {
  const defs = singboxSchema.$defs ?? {}
  const outbounds = {}
  for (const [name, schema] of Object.entries(defs)) {
    if (!name.endsWith('OutboundOptions')) continue
    const type = schemaTypeName(schema)
    if (!type || !MANAGED_SINGBOX_TYPES.has(type)) continue
    outbounds[type] = {
      schemaRef: `#/$defs/${name}`,
      fields: [...collectProperties(schema)].sort(),
      required: Array.isArray(schema.required) ? schema.required : [],
    }
  }
  return sortObject(outbounds)
}

function extractSingboxEndpoints() {
  const defs = singboxSchema.$defs ?? {}
  const endpoints = {}
  for (const [name, schema] of Object.entries(defs)) {
    if (!name.endsWith('EndpointOptions')) continue
    const type = schemaTypeName(schema)
    if (!type || !MANAGED_SINGBOX_ENDPOINT_TYPES.has(type)) continue
    endpoints[type] = {
      schemaRef: `#/$defs/${name}`,
      fields: [...collectProperties(schema)].sort(),
      required: Array.isArray(schema.required) ? schema.required : [],
    }
  }
  return sortObject(endpoints)
}

function extractMihomoProxies() {
  const entries = mihomoSchema.definitions?.proxies?.items?.anyOf ?? []
  const proxies = {}
  for (const entry of entries) {
    const type = findConstType(entry)
    if (!type || !MANAGED_MIHOMO_TYPES.has(type)) continue
    proxies[type] = {
      fields: [...collectProperties(entry)].sort(),
      required: Array.isArray(entry.required) ? entry.required : [],
    }
  }
  return sortObject(proxies)
}

function findConstType(schema) {
  const direct = schemaTypeName(schema)
  if (direct) return direct
  for (const key of ['allOf', 'anyOf', 'oneOf']) {
    const entries = schema?.[key]
    if (!Array.isArray(entries)) continue
    for (const entry of entries) {
      const nested = findConstType(entry)
      if (nested) return nested
    }
  }
  return undefined
}

function sortObject(object) {
  return Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b)))
}

const metadata = {
  sources: {
    singbox: {
      package: '@black-duty/sing-box-schema',
      version: singboxPackage.version,
      schema: '@black-duty/sing-box-schema/schema.json',
    },
    mihomo: {
      package: 'meta-json-schema',
      version: mihomoPackage.version,
      schema: 'meta-json-schema/schemas/meta-json-schema.json',
    },
  },
  singboxOutbounds: extractSingboxOutbounds(),
  singboxEndpoints: extractSingboxEndpoints(),
  mihomoProxies: extractMihomoProxies(),
}

const contents = `// Generated by packages/types/scripts/generate-protocol-metadata.mjs
// Do not edit by hand.

export const GENERATED_PROTOCOL_SCHEMA_METADATA = ${JSON.stringify(metadata, null, 2)} as const
`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, contents)
console.log(`Generated ${path.relative(process.cwd(), outFile)}`)
